/**
 * Enum für die Verpflegungsarten, die in einem Hotel gebucht werden können.
 * <p>
 * Enthält die Standardoptionen: Vollpension, Halbpension und Frühstück.
 * </p>
 */
public enum Verpflegung {
    VOLLPENSION,   // Frühstück, Mittag- und Abendessen
    HALBPENSION,   // Frühstück und Abendessen
    FRUEHSTUECK    // Nur Frühstück
}